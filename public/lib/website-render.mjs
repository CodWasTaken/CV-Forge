import { renderCss, renderScript, themeTokens } from './website-theme.mjs';
import { renderAbout, renderSkills, renderExperience, renderProjects, renderCredentials, renderContact, primaryCta } from './website-sections.mjs';
import { normalizeWebsite } from './website-config.mjs';
import { initials, navLabel, escapeHtml, escapeAttribute } from './website-utils.mjs';

export function renderWebsiteFiles(profile = {}, websiteInput = {}) {
  const website = normalizeWebsite(websiteInput, profile);
  const theme = themeTokens(website.theme, website.accent);
  const sections = Object.fromEntries([
    ['about', renderAbout(profile, website)],
    ['skills', renderSkills(profile, website)],
    ['experience', renderExperience(profile, website)],
    ['projects', renderProjects(profile, website)],
    ['credentials', renderCredentials(profile)],
    ['contact', renderContact(profile, website)]
  ]);
  const name = profile.personal?.name || 'Professional CV';
  const description = website.subheadline || profile.summary || `${name} portfolio and CV`;
  const body = website.sectionOrder.map((section) => sections[section]).filter(Boolean).join('\n');

  const indexHtml = `<!doctype html>
<html lang="en" data-theme="${escapeAttribute(website.theme)}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="${escapeAttribute(description)}">
  <meta name="color-scheme" content="${theme.colorScheme}">
  <meta name="theme-color" content="${escapeAttribute(theme.background)}">
  <title>${escapeHtml(name)} — Portfolio & CV</title>
  <link rel="stylesheet" href="styles.css">
  <script src="script.js" defer></script>
</head>
<body>
  <a class="skip-link" href="#main">Skip to content</a>
  <header class="site-header">
    <a class="wordmark" href="#top" aria-label="Home">${escapeHtml(initials(name))}</a>
    <nav aria-label="Primary navigation">
      ${website.sectionOrder.filter((section) => sections[section]).map((section) => `<a href="#${section}">${escapeHtml(navLabel(section))}</a>`).join('')}
    </nav>
  </header>

  <main id="main">
    <section class="hero" id="top">
      <div class="hero-glow" aria-hidden="true"></div>
      <div class="hero-copy reveal">
        <p class="eyebrow">${escapeHtml(website.heroKicker)}</p>
        <h1>${escapeHtml(website.headline)}</h1>
        <p class="hero-summary">${escapeHtml(website.subheadline)}</p>
        <div class="hero-actions">
          ${primaryCta(profile, website)}
          <a class="button button-ghost" href="#experience">Explore experience</a>
        </div>
      </div>
      <aside class="profile-card reveal" aria-label="Profile details">
        <p class="profile-name">${escapeHtml(name)}</p>
        ${profile.personal?.title ? `<p>${escapeHtml(profile.personal.title)}</p>` : ''}
        ${profile.personal?.location ? `<span>${escapeHtml(profile.personal.location)}</span>` : ''}
        ${profile.skills?.length ? `<div class="mini-skills">${profile.skills.slice(0, 6).map((skill) => `<span>${escapeHtml(skill)}</span>`).join('')}</div>` : ''}
      </aside>
    </section>
    ${body}
  </main>

  <footer class="site-footer">
    <p>© <span id="year"></span> ${escapeHtml(name)}.</p>
    <p>Static portfolio generated by CV Forge.</p>
  </footer>
</body>
</html>`;

  return {
    indexHtml,
    stylesCss: renderCss(theme),
    scriptJs: renderScript(),
    profileJson: JSON.stringify(profile, null, 2),
    siteJson: JSON.stringify(website, null, 2)
  };
}
